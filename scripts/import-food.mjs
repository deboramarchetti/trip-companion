// Builds src/data/food.ts from researched JSON files (one per region).
//   node scripts/import-food.mjs path/to/eat-*.json
// Each entry: { id, name, localName?, address, lat?, lng?, meals[], dish, description,
//               price, hours?, sources[], days[], notes? }
import { readFileSync, writeFileSync } from 'node:fs';

const CITY_BY_PREFIX = { han: 'hanoi', nb: 'ninh-binh', ha: 'hoi-an', dn: 'hoi-an', hue: 'hue', sg: 'ho-chi-minh', cc: 'ho-chi-minh', bt: 'ho-chi-minh' };
const MEALS = new Set(['breakfast', 'lunch', 'dinner', 'snack', 'coffee', 'drinks']);

const out = [];
const seen = new Set();
for (const file of process.argv.slice(2)) {
  for (const e of JSON.parse(readFileSync(file, 'utf8'))) {
    const prefix = e.id.split('-')[0];
    const cityId = CITY_BY_PREFIX[prefix];
    if (!cityId) throw new Error(`${file}: unknown id prefix in ${e.id}`);
    if (seen.has(e.id)) throw new Error(`duplicate id ${e.id}`);
    seen.add(e.id);
    const meals = e.meals.filter((m) => MEALS.has(m));
    const spot = {
      id: e.id,
      name: e.name.trim(),
      ...(e.localName && e.localName !== e.name ? { localName: e.localName } : {}),
      cityId,
      kind: meals.every((m) => m === 'coffee' || m === 'drinks') ? 'cafe' : 'restaurant',
      ...(e.address ? { address: e.address } : { mapsQuery: `${e.name}, ${cityId}` }),
      ...(typeof e.lat === 'number' && typeof e.lng === 'number' ? { coords: { lat: e.lat, lng: e.lng, verified: false } } : {}),
      meals,
      ...(e.dish ? { dish: e.dish } : {}),
      ...(e.description ? { description: e.description } : {}),
      ...(e.price ? { price: e.price } : {}),
      ...(e.hours ? { hours: e.hours } : {}),
      ...(e.sources?.length ? { sources: e.sources } : {}),
      days: [...new Set(e.days)].sort(),
      ...(e.notes ? { notes: e.notes } : {}),
    };
    out.push(spot);
  }
}

const body = `import type { FoodSpot } from './types';

/**
 * AUTO-GENERATED by scripts/import-food.mjs — where to eat, by day.
 * Researched in Nov 2026 from Michelin Guide Vietnam, TripAdvisor, Lonely Planet,
 * VnExpress and food guides. Recommendations only (not reservations); opening
 * hours vary between sources — check before going.
 */
export const food: FoodSpot[] = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL('../src/data/food.ts', import.meta.url), body);
console.log(`wrote src/data/food.ts: ${out.length} places`);
