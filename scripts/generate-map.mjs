// Generates src/map/vietnamGeo.ts — a static, offline SVG map of Vietnam
// (plus faint neighbours) from Natural Earth data (world-atlas, 50m).
// Run: npm run map:generate
import { readFileSync, writeFileSync } from 'node:fs';
import { geoMercator, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-50m.json', import.meta.url)));
const countries = feature(topo, topo.objects.countries);
const VN = '704';
const NEIGHBOURS = { '418': 'Laos', '116': 'Cambodia', '156': 'China', '764': 'Thailand' };
const vn = countries.features.find((f) => f.id === VN);

// Viewport: tall portrait frame that fits the S-shaped country.
const W = 400, H = 760, PAD = 28;
const projection = geoMercator().fitExtent([[PAD, PAD], [W - PAD, H - PAD]], vn);
const path = geoPath(projection);
const round = (d) => d.replace(/(\d+\.\d{1})\d+/g, '$1');

const neighbours = countries.features
  .filter((f) => NEIGHBOURS[f.id])
  .map((f) => ({ name: NEIGHBOURS[f.id], d: round(path(f)) }));

const out = `// AUTO-GENERATED by scripts/generate-map.mjs — do not edit by hand.
// Source: Natural Earth via world-atlas (public domain). Mercator projection.
export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};
/** d3 geoMercator parameters so points can be projected without d3 at runtime. */
export const PROJECTION = { scale: ${projection.scale()}, translate: [${projection.translate().join(', ')}] as [number, number] };
export const VIETNAM_PATH = ${JSON.stringify(round(path(vn)))};
export const NEIGHBOUR_PATHS: { name: string; d: string }[] = ${JSON.stringify(neighbours)};
`;
writeFileSync(new URL('../src/map/vietnamGeo.ts', import.meta.url), out);
console.log('wrote src/map/vietnamGeo.ts', (out.length / 1024).toFixed(1) + 'KB');
